CREATE TABLE IF NOT EXISTS electricity_rate_sets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(64) NOT NULL,
    version_code VARCHAR(128) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    source_organization VARCHAR(200) NOT NULL,
    source_document VARCHAR(200) NOT NULL,
    source_url VARCHAR(500),
    approval_reference VARCHAR(200) NOT NULL,
    source_checksum CHAR(64),
    currency CHAR(3) NOT NULL,
    includes_tax BOOLEAN NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT electricity_rate_sets_version_key UNIQUE (provider, version_code),
    CONSTRAINT electricity_rate_sets_date_check CHECK (effective_to IS NULL OR effective_to > effective_from),
    CONSTRAINT electricity_rate_sets_status_check CHECK (status IN ('DRAFT', 'AUTHORITATIVE', 'RETIRED')),
    CONSTRAINT electricity_rate_sets_checksum_check CHECK (source_checksum IS NULL OR source_checksum ~ '^[0-9a-fA-F]{64}$')
);

ALTER TABLE electricity_rate_sets
    DROP CONSTRAINT IF EXISTS electricity_rate_sets_authoritative_no_overlap;
ALTER TABLE electricity_rate_sets
    ADD CONSTRAINT electricity_rate_sets_authoritative_no_overlap
    EXCLUDE USING gist (
        provider WITH =,
        daterange(effective_from, COALESCE(effective_to, 'infinity'::date), '[)') WITH &&
    ) WHERE (status IN ('AUTHORITATIVE', 'RETIRED'));

CREATE INDEX IF NOT EXISTS idx_electricity_rate_sets_effective
    ON electricity_rate_sets (provider, effective_from, effective_to);

CREATE TABLE IF NOT EXISTS electricity_tariff_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_code VARCHAR(100) NOT NULL UNIQUE,
    electricity_tariff VARCHAR(32) NOT NULL,
    billing_method VARCHAR(32) NOT NULL,
    usage_class VARCHAR(64),
    calculator_kind VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT electricity_tariff_plans_tariff_check CHECK (electricity_tariff IN ('LIGHTING_COMMERCIAL', 'LIGHTING_NONCOMMERCIAL')),
    CONSTRAINT electricity_tariff_plans_method_check CHECK (billing_method = 'NON_TOU'),
    CONSTRAINT electricity_tariff_plans_calculator_check CHECK (calculator_kind = 'PROGRESSIVE_NON_TOU'),
    CONSTRAINT electricity_tariff_plans_usage_check CHECK (
        (electricity_tariff = 'LIGHTING_COMMERCIAL' AND usage_class IS NULL)
        OR (electricity_tariff = 'LIGHTING_NONCOMMERCIAL' AND usage_class IN ('RESIDENTIAL', 'NON_RESIDENTIAL_NONCOMMERCIAL'))
    )
);

CREATE TABLE IF NOT EXISTS electricity_rate_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_set_id BIGINT NOT NULL REFERENCES electricity_rate_sets(id) ON DELETE RESTRICT,
    tariff_plan_id BIGINT NOT NULL REFERENCES electricity_tariff_plans(id) ON DELETE RESTRICT,
    minimum_monthly_charge NUMERIC(20,6) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT electricity_rate_plans_set_plan_key UNIQUE (rate_set_id, tariff_plan_id),
    CONSTRAINT electricity_rate_plans_minimum_check CHECK (minimum_monthly_charge >= 0)
);

CREATE TABLE IF NOT EXISTS electricity_rate_tiers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_plan_id BIGINT NOT NULL REFERENCES electricity_rate_plans(id) ON DELETE RESTRICT,
    season VARCHAR(20) NOT NULL,
    tier_order INTEGER NOT NULL,
    lower_kwh NUMERIC(20,6) NOT NULL,
    upper_kwh NUMERIC(20,6),
    rate_per_kwh NUMERIC(20,6) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT electricity_rate_tiers_key UNIQUE (rate_plan_id, season, tier_order),
    CONSTRAINT electricity_rate_tiers_season_check CHECK (season IN ('SUMMER', 'NON_SUMMER')),
    CONSTRAINT electricity_rate_tiers_order_check CHECK (tier_order > 0),
    CONSTRAINT electricity_rate_tiers_bounds_check CHECK (lower_kwh >= 0 AND (upper_kwh IS NULL OR upper_kwh > lower_kwh)),
    CONSTRAINT electricity_rate_tiers_rate_check CHECK (rate_per_kwh >= 0)
);

CREATE INDEX IF NOT EXISTS idx_electricity_rate_tiers_lookup
    ON electricity_rate_tiers (rate_plan_id, season, tier_order);

