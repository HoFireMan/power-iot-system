CREATE OR REPLACE FUNCTION billing_rate_set_immutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status IN ('AUTHORITATIVE', 'RETIRED') THEN
        IF TG_OP = 'DELETE' THEN
            RAISE EXCEPTION 'authoritative electricity rate sets are immutable';
        END IF;
        IF OLD.status = 'AUTHORITATIVE'
           AND NEW.status = 'AUTHORITATIVE'
           AND OLD.effective_to IS NULL
           AND NEW.effective_to IS NOT NULL
           AND NEW.provider = OLD.provider
           AND NEW.version_code = OLD.version_code
           AND NEW.effective_from = OLD.effective_from
           AND NEW.source_organization = OLD.source_organization
           AND NEW.source_document = OLD.source_document
           AND NEW.source_url IS NOT DISTINCT FROM OLD.source_url
           AND NEW.approval_reference = OLD.approval_reference
           AND NEW.source_checksum IS NOT DISTINCT FROM OLD.source_checksum
           AND NEW.currency = OLD.currency
           AND NEW.includes_tax = OLD.includes_tax
           AND NEW.created_at = OLD.created_at THEN
            RETURN NEW;
        END IF;
        IF OLD.status = 'AUTHORITATIVE' AND NEW.status = 'RETIRED'
           AND NEW.provider = OLD.provider
           AND NEW.version_code = OLD.version_code
           AND NEW.effective_from = OLD.effective_from
           AND NEW.effective_to IS NOT DISTINCT FROM OLD.effective_to
           AND NEW.source_organization = OLD.source_organization
           AND NEW.source_document = OLD.source_document
           AND NEW.source_url IS NOT DISTINCT FROM OLD.source_url
           AND NEW.approval_reference = OLD.approval_reference
           AND NEW.source_checksum IS NOT DISTINCT FROM OLD.source_checksum
           AND NEW.currency = OLD.currency
           AND NEW.includes_tax = OLD.includes_tax
           AND NEW.created_at = OLD.created_at THEN
            RETURN NEW;
        END IF;
        RAISE EXCEPTION 'authoritative electricity rate sets are immutable';
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$;

