INSERT INTO carbon_factor_rates (set_id, tariff_code, factor_kgco2e_per_kwh)
SELECT sets.id, rates.tariff_code, rates.factor_kgco2e_per_kwh
FROM carbon_factor_sets AS sets
CROSS JOIN (VALUES
    ('LIGHTING_COMMERCIAL', 0.466::numeric),
    ('LOW_VOLTAGE', 0.466::numeric),
    ('HIGH_VOLTAGE', 0.466::numeric),
    ('EXTRA_HIGH_VOLTAGE', 0.466::numeric),
    ('LIGHTING_NONCOMMERCIAL', 0.471::numeric),
    ('PACKAGE_LIGHTING', 0.471::numeric)
) AS rates(tariff_code, factor_kgco2e_per_kwh)
WHERE sets.version_year = 2025 AND sets.roc_year = 114
ON CONFLICT (set_id, tariff_code) DO UPDATE SET
    factor_kgco2e_per_kwh = EXCLUDED.factor_kgco2e_per_kwh;
