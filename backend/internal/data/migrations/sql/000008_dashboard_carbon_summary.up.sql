ALTER TABLE shops
    ADD COLUMN IF NOT EXISTS electricity_tariff VARCHAR(32);
ALTER TABLE shops
    DROP CONSTRAINT IF EXISTS shops_electricity_tariff_check;
ALTER TABLE shops
    ADD CONSTRAINT shops_electricity_tariff_check CHECK (
        electricity_tariff IS NULL OR electricity_tariff IN (
            'LIGHTING_COMMERCIAL', 'LOW_VOLTAGE', 'HIGH_VOLTAGE',
            'EXTRA_HIGH_VOLTAGE', 'LIGHTING_NONCOMMERCIAL', 'PACKAGE_LIGHTING'
        )
    );

CREATE TABLE IF NOT EXISTS carbon_factor_sets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization VARCHAR(200) NOT NULL,
    document_title VARCHAR(200) NOT NULL,
    source_url VARCHAR(500) NOT NULL,
    version_year INTEGER NOT NULL,
    roc_year INTEGER NOT NULL,
    unit VARCHAR(32) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT carbon_factor_sets_version_key UNIQUE (version_year, roc_year),
    CONSTRAINT carbon_factor_sets_unit_check CHECK (unit = 'kgCO2e/kWh')
);

CREATE UNIQUE INDEX IF NOT EXISTS carbon_factor_sets_one_active
    ON carbon_factor_sets (is_active) WHERE is_active;

CREATE TABLE IF NOT EXISTS carbon_factor_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_id BIGINT NOT NULL REFERENCES carbon_factor_sets(id) ON DELETE CASCADE,
    tariff_code VARCHAR(32) NOT NULL,
    factor_kgco2e_per_kwh NUMERIC(10,6) NOT NULL,
    CONSTRAINT carbon_factor_rates_set_tariff_key UNIQUE (set_id, tariff_code),
    CONSTRAINT carbon_factor_rates_tariff_check CHECK (tariff_code IN (
        'LIGHTING_COMMERCIAL', 'LOW_VOLTAGE', 'HIGH_VOLTAGE',
        'EXTRA_HIGH_VOLTAGE', 'LIGHTING_NONCOMMERCIAL', 'PACKAGE_LIGHTING'
    )),
    CONSTRAINT carbon_factor_rates_nonnegative_check CHECK (factor_kgco2e_per_kwh >= 0)
);

